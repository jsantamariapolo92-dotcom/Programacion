package ud2.ejemplos;

public class EjemplosBucle {
    public static void main(String[] args) {

        // Bucle de cero repeticiones
        int contador = -8;
        while (contador >= 0) {
            // Cuerpo del bucle
            System.out.println(contador);
        }

        while (contador < 0) {
            // Cuerpo del bucle
            System.out.println(contador);
        }

    }
}
